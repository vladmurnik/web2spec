"""Scraping specs: a compact, executable description of a list/detail page.

A spec is intentionally not free-form code. The model emits selectors and
field mappings; a deterministic renderer turns them into Python or executes
them directly. This keeps a 0.5B model inside a task it can actually learn.
"""

from __future__ import annotations

import json
from typing import Any
from urllib.parse import urljoin

from bs4 import BeautifulSoup
from pydantic import BaseModel, ConfigDict, Field, ValidationError

SPEC_VERSION = 1


class SpecError(ValueError):
    """Invalid spec or HTML that cannot be processed."""


class FieldSpec(BaseModel):
    model_config = ConfigDict(extra="forbid")

    selector: str = Field(min_length=1, max_length=300)
    attr: str | None = Field(default=None, max_length=50)
    required: bool = False


class PaginationSpec(BaseModel):
    model_config = ConfigDict(extra="forbid")

    selector: str = Field(min_length=1, max_length=300)
    attr: str = "href"
    max_pages: int = Field(default=3, ge=1, le=50)


class ScrapingSpec(BaseModel):
    """A page-level or item-level extraction plan."""

    model_config = ConfigDict(extra="forbid")

    version: int = SPEC_VERSION
    item_selector: str | None = Field(default=None, max_length=300)
    fields: dict[str, FieldSpec] = Field(min_length=1)
    pagination: PaginationSpec | None = None

    def field_names(self) -> list[str]:
        return list(self.fields)


def load_spec(raw: Any) -> ScrapingSpec:
    if isinstance(raw, str):
        try:
            raw = json.loads(raw)
        except json.JSONDecodeError as exc:
            raise SpecError(f"spec is not JSON: {exc}") from exc
    if not isinstance(raw, dict):
        raise SpecError("spec must be a JSON object")
    try:
        spec = ScrapingSpec.model_validate(raw)
    except ValidationError as exc:
        first = exc.errors()[0]
        location = ".".join(str(part) for part in first["loc"]) or "<root>"
        raise SpecError(f"{location}: {first['msg']}") from exc
    if spec.version != SPEC_VERSION:
        raise SpecError(f"unsupported spec version: {spec.version}")
    return spec


def _value(node: Any, field: FieldSpec, base_url: str | None) -> str | None:
    element = node.select_one(field.selector)
    if element is None:
        return None
    if field.attr:
        raw = element.get(field.attr)
        if raw is None:
            return None
        text = str(raw).strip()
        if base_url and field.attr in {"href", "src"}:
            text = urljoin(base_url, text)
    else:
        text = element.get_text(" ", strip=True)
    return text or None


def extract(spec: ScrapingSpec, html: str, *, base_url: str | None = None) -> Any:
    """Execute a spec against one HTML document.

    Returns a list of dicts when ``item_selector`` is set, otherwise one dict.
    Missing optional fields are omitted; missing required fields become ``None``
    so callers can measure recall instead of silently dropping the row.
    """

    if not html or "<" not in html:
        raise SpecError("html is empty or not HTML")
    soup = BeautifulSoup(html, "lxml")

    if spec.item_selector:
        nodes = soup.select(spec.item_selector)
        if not nodes:
            return []
        rows = []
        for node in nodes:
            row: dict[str, Any] = {}
            for name, field in spec.fields.items():
                value = _value(node, field, base_url)
                if value is None and not field.required:
                    continue
                row[name] = value
            if row:
                rows.append(row)
        return rows

    row = {}
    for name, field in spec.fields.items():
        value = _value(soup, field, base_url)
        if value is None and not field.required:
            continue
        row[name] = value
    return row


def next_page_url(spec: ScrapingSpec, html: str, *, base_url: str | None = None) -> str | None:
    """Resolve the pagination URL declared by the spec, if any."""

    if spec.pagination is None:
        return None
    soup = BeautifulSoup(html, "lxml")
    element = soup.select_one(spec.pagination.selector)
    if element is None:
        return None
    raw = element.get(spec.pagination.attr)
    if not raw:
        return None
    raw = str(raw).strip()
    return urljoin(base_url, raw) if base_url else raw


def _literal(value: str | None) -> str:
    return repr(value)


def render_python(spec: ScrapingSpec, *, function_name: str = "scrape") -> str:
    """Render a standalone requests+bs4 module from a spec.

    The generated code is deliberately plain: one selector per field, no
    inferred magic. It is meant to be reviewable and testable.
    """

    lines = [
        '"""Generated by web2spec. Review selectors before production use."""',
        "",
        "from urllib.parse import urljoin",
        "",
        "import requests",
        "from bs4 import BeautifulSoup",
        "",
        "",
        f"def {function_name}(html: str, base_url: str | None = None):",
        '    soup = BeautifulSoup(html, "lxml")',
    ]
    if spec.item_selector:
        lines.append("    rows = []")
        lines.append(f"    for node in soup.select({_literal(spec.item_selector)}):")
        lines.append("        row = {}")
        for name, field in spec.fields.items():
            lines.append(f"        element = node.select_one({_literal(field.selector)})")
            lines.append("        if element is None:")
            if field.required:
                lines.append(f"            row[{name!r}] = None")
            else:
                lines.append("            continue")
            lines.append("        else:")
            if field.attr:
                lines.append(f"            value = element.get({field.attr!r})")
                lines.append("            if value is not None:")
                lines.append("                value = str(value).strip()")
                if field.attr in {"href", "src"}:
                    lines.append("                if base_url:")
                    lines.append("                    value = urljoin(base_url, value)")
            else:
                lines.append('            value = element.get_text(" ", strip=True)')
            lines.append(f"            row[{name!r}] = value or None")
        lines.append("        if row:")
        lines.append("            rows.append(row)")
        lines.append("    return rows")
    else:
        lines.append("    row = {}")
        for name, field in spec.fields.items():
            lines.append(f"    element = soup.select_one({_literal(field.selector)})")
            lines.append("    if element is None:")
            if field.required:
                lines.append(f"        row[{name!r}] = None")
            else:
                lines.append("        pass")
            lines.append("    else:")
            if field.attr:
                lines.append(f"        value = element.get({field.attr!r})")
                lines.append("        if value is not None:")
                lines.append("            value = str(value).strip()")
                if field.attr in {"href", "src"}:
                    lines.append("            if base_url:")
                    lines.append("                value = urljoin(base_url, value)")
            else:
                lines.append('        value = element.get_text(" ", strip=True)')
            lines.append(f"        row[{name!r}] = value or None")
        lines.append("    return row")

    if spec.pagination is not None:
        lines.extend(
            [
                "",
                "",
                "def next_page(html: str, base_url: str | None = None):",
                '    soup = BeautifulSoup(html, "lxml")',
                f"    element = soup.select_one({_literal(spec.pagination.selector)})",
                "    if element is None:",
                "        return None",
                f"    value = element.get({spec.pagination.attr!r})",
                "    if not value:",
                "        return None",
                "    value = str(value).strip()",
                "    return urljoin(base_url, value) if base_url else value",
            ]
        )
    lines.append("")
    return "\n".join(lines)
